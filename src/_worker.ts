const legacyHandler: ExportedHandler<Env> = {
  async fetch(request, env, ctx) {
    // MCP connector OAuth consent screen (0015). workers-oauth-provider
    // auto-serves /oauth/token, /oauth/register and the .well-known metadata,
    // but delegates the authorize endpoint here (env.OAUTH_PROVIDER is injected
    // by the provider). Handle it before agent routing / auth gates.
    const authorizeResponse = await handleOAuthAuthorize(request, env);
    if (authorizeResponse) return authorizeResponse;

    // Showroom Scout spends real Gemini and Google Maps quota on every run, so
    // its agent surface (HTTP + WebSocket) is gated before `routeAgentRequest`,
    // which otherwise runs ahead of every auth check in this Worker.
    //
    // Scoped deliberately to this one agent rather than all of them: the other
    // agent namespaces predate this gate and changing their auth posture is a
    // separate decision. That means the remaining `/agents/*` namespaces are
    // still open — see the note in the Showroom Scout README.
    const agentUrl = new URL(request.url);
    if (agentUrl.pathname.startsWith("/agents/showroom-scout")) {
      if (!(await isRequestAuthenticated(request, env))) {
        return new Response(JSON.stringify({ error: "Unauthorized" }), {
          status: 401,
          headers: { "content-type": "application/json" },
        });
      }
    }

    const agentResponse = await routeAgentRequest(request, env);
    if (agentResponse) return agentResponse;

    const url = new URL(request.url);

    // Legacy-path 301s (rebrand + admin-route normalization). Runs before auth so
    // old bookmarks land on the new URL (and then hit the /admin auth gate there).
    for (const [from, to] of LEGACY_REDIRECTS) {
      if (url.pathname === from || url.pathname.startsWith(`${from}/`)) {
        const rest = url.pathname.slice(from.length);
        return Response.redirect(`${url.origin}${to}${rest}${url.search}`, 301);
      }
    }

    // Device-scoped landing preference: an authed device that has chosen a
    // default landing page (from /admin/config/device) is redirected there when
    // it hits the app root exactly. The choice lives in D1 keyed by the device's
    // cookie id, so each device routes independently (Tesla → drives, phone →
    // showrooms). Only fires for authed devices; unauthed root hits fall through
    // to the normal home/login. Path is validated to block open-redirects.
    if (url.pathname === "/") {
      const deviceId = getDeviceIdFromRequest(request);
      // Auth is always required — a device that was an admin in the past still
      // must present a VALID admin cookie. An expired/absent cookie falls through
      // to the normal home/login and never gets an auto-redirect.
      if (await isRequestAuthenticated(request, env)) {
        // Active-drive override: while ONE drive list is active, admin devices
        // auto-land on it (temporary — reverts to the device's normal landing
        // once no drive is active). Takes precedence over the device pref.
        const drivePath = await getActiveDriveLandingPath(env);
        if (drivePath && isSafeInternalPath(drivePath)) {
          return Response.redirect(`${url.origin}${drivePath}`, 302);
        }
        // Otherwise fall back to the device's chosen landing page.
        if (deviceId) {
          const landing = await getDeviceLandingPath(env, deviceId);
          if (landing && landing !== "/" && isSafeInternalPath(landing)) {
            return Response.redirect(`${url.origin}${landing}`, 302);
          }
        }
      }
    }

    const protectedPaths = [
      "/admin",
      "/uploads",
      "/photo-edits",
      "/review",
      "/budget-tracker",
      "/budget-dashboard",
    ];

    const isProtectedPath = protectedPaths.some(
      (path) => url.pathname === path || url.pathname.startsWith(`${path}/`),
    );

    if (
      url.pathname.startsWith("/api/realtime/estimates") ||
      url.pathname.startsWith("/api/realtime/plans")
    ) {
      // Both surfaces fan out through the same EstimateCollabHub DO, keyed by the
      // `room` param. Plan/task progress uses room `plan:<planSlug>` so an open
      // preview-changelog viewer gets a live poke when a task's status changes.
      const room = url.searchParams.get("room")?.trim() || "global";
      const stub = env.ESTIMATE_COLLAB.getByName(room);
      return stub.fetch(request);
    }

    // Real-time floor-plan sessions: /api/room/:roomName/ws (WebSocket upgrade +
    // /health). The Worker is a stateless gateway — it routes by room name to the
    // matching FloorplanSessionDO instance and offloads the socket to the DO.
    const floorplanRoom = url.pathname.match(/^\/api\/room\/([^/]+)\/(ws|health)$/);
    if (floorplanRoom) {
      const roomName = decodeURIComponent(floorplanRoom[1]);
      const stub = env.FLOORPLAN_SESSION.getByName(roomName);
      return stub.fetch(request);
    }

    // Handle API routes with Hono
    if (
      url.pathname.startsWith("/api/") ||
      url.pathname === "/api-docs" ||
      url.pathname === "/openapi.json" ||
      url.pathname === "/swagger" ||
      url.pathname === "/scalar" ||
      url.pathname === "/context"
    ) {
      return honoApp.fetch(request, env, ctx);
    }

    if (isProtectedPath) {
      const authenticated = await isRequestAuthenticated(request, env);
      if (!authenticated) {
        const redirect = new URL("/access", url.origin);
        redirect.searchParams.set("next", `${url.pathname}${url.search}`);
        return Response.redirect(redirect.toString(), 302);
      }
    }

    // Let Astro handle everything else (SSR and static assets via env.ASSETS)
    const astroResponse = await astroHandler.fetch!(request, env, ctx);

    // Studio artifact runtime (/studio-runtime) renders inside a
    // `sandbox="allow-scripts"` iframe, which gives the frame an OPAQUE origin.
    // Its Astro island hydrates by fetching `/_astro/*` module scripts, and a
    // module fetch from an opaque origin is cross-origin — so without CORS
    // headers the browser blocks it and the island never mounts (blank frame).
    // Build assets are public app code, so it's safe to allow any origin.
    if (url.pathname.startsWith("/_astro/")) {
      const headers = new Headers(astroResponse.headers);
      headers.set("Access-Control-Allow-Origin", "*");
      headers.set("Cross-Origin-Resource-Policy", "cross-origin");
      // Cached assets return a null-body status (304 on conditional GETs, 204);
      // passing a body to `new Response` for those throws a TypeError in Workers.
      const body = [204, 304].includes(astroResponse.status) ? null : astroResponse.body;
      return new Response(body, {
        status: astroResponse.status,
        statusText: astroResponse.statusText,
        headers,
      });
    }

    return astroResponse;
  },
  async email(message, env, ctx) {
    // Inbound email → routing layer. The router applies auto-reply/loop
    // protection, resolves the recipient address to a route (invoices /
    // contracts / catch-all), rejects unknown recipients, and dispatches to
    // the background processing pipeline. See src/backend/services/email/.
    const { handleInboundEmail } = await import("./backend/services/email");
    await handleInboundEmail(message, env, ctx);
  },
  async scheduled(event, env, ctx) {
    // Gate by cron expression so each registered trigger fires its own job.
    // The existing 14:00 UTC trigger runs the permit sync; the new master-tick
    // "* * * * *" reads `system_cron_schedules` and fires any due workflows.
    // Weekly provider price refresh. Its own trigger rather than a rider on the
    // daily job: it hits four external endpoints and must not share a failure
    // budget with the permit sync.
    if (event.cron === "0 9 * * 1") {
      ctx.waitUntil(refreshPricingCatalog(env).then(() => undefined));
      return;
    }
    if (event.cron === "0 14 * * *") {
      ctx.waitUntil(runPermitSync(env));
      // Prune the agent run ledger. Daily, not per-minute: a sweep that finds
      // nothing 1,439 times a day is pure waste, and an append-only ledger
      // written by every instrumented surface is exactly how a cost-monitoring
      // feature would otherwise become its own D1 row-read cost story.
      ctx.waitUntil(pruneAgentRuns(env));
      return;
    }
    if (event.cron === "* * * * *") {
      ctx.waitUntil(dispatchDueWorkflows(env));
      // Self-heal image uploads stranded by transient Workers AI capacity
      // errors (or whose workflow never started) without manual reprocessing.
      ctx.waitUntil(autoHealImageUploads(env));
      ctx.waitUntil(monitorShowroomSourcingCoverage(env));
      // Enforce the daytime window: a drive can only be active 07:00–20:00
      // Pacific, so deactivate one that has run past the close. Cheap (one
      // indexed read; a write only on the boundary tick).
      ctx.waitUntil(
        enforceStreamWindow(env)
          .then((r) => {
            if (r.deactivated) console.log(`[scheduled] drive '${r.slug}' deactivated: window closed`);
          })
          .catch((err) => console.error("[scheduled] stream window enforce failed:", err)),
      );
      // Vehicle polling — the FALLBACK ingest path. Self-gates: no active drive,
      // the streaming DO is carrying ingest, or a poll within the configured
      // cadence, and it's one indexed D1 read.
      ctx.waitUntil(
        pollVehicleForActiveDrive(env)
          .then((r) => {
            if (r.polled && r.latitude != null) {
              console.log(
                `[scheduled] tesla poll: shift=${r.shiftState} matched=${r.matchedStop?.name ?? "none"} ` +
                  `home=${r.homeArrival?.reason}`,
              );
            }
          })
          .catch((err) => console.error("[scheduled] tesla poll failed:", err)),
      );
      // One-shot re-enrichment of showroom website/hours/address from Google
      // Places (0108/0109 dropped the legacy columns before backfill). Processes
      // a small batch per tick and no-ops once every place_id store is done.
      ctx.waitUntil(
        backfillShowroomPlacesData(env)
          .then((r) => {
            if (r.processed > 0) {
              console.log(
                `[scheduled] showroom places backfill: processed=${r.processed} remaining=${r.remaining}`,
              );
            }
          })
          .catch((err) => console.error("[scheduled] showroom places backfill failed:", err)),
      );
      return;
    }
    if (event.cron === "15 */4 * * *") {
      // Gmail comms hub (0013 P3-07): bounded ingestion every 4 hours — see
      // wrangler.jsonc for why this is a dedicated trigger rather than
      // piggybacking the per-minute master tick.
      ctx.waitUntil(
        ingestCompanyEmails(env)
          .then((result) =>
            console.log(
              `[scheduled] gmail ingestion: companies=${result.companies} threads=${result.threads} messages=${result.messages}`,
            ),
          )
          .catch((err) => console.error("[scheduled] gmail ingestion failed:", err)),
      );
      // Safety-net: pull anything the user manually dropped into the
      // `core-remodel/inbox` Gmail label, then unlabel it. See inbox-label.ts.
      ctx.waitUntil(
        ingestInboxLabel(env)
          .then((r) => {
            if (r.found > 0) {
              console.log(
                `[scheduled] gmail inbox-label safety-net: found=${r.found} ingested=${r.ingested} skipped=${r.skipped}`,
              );
            }
          })
          .catch((err) => console.error("[scheduled] gmail inbox-label ingestion failed:", err)),
      );
      return;
    }
    if (event.cron === "30 13 * * 1") {
      // Weekly showroom sale/clearance sweep. Re-scans every WEBSITE_CLEARANCE
      // link and records a showroom_store_sales snapshot ONLY
      // when the page content actually changed vs the last scrape.
      ctx.waitUntil(
        sweepShowroomSales(env)
          .then((r) =>
            console.log(
              `[scheduled] showroom sales sweep: pages=${r.pagesScanned} stores=${r.storesScanned} ` +
                `recorded=${r.recorded} unchanged=${r.unchanged} empty=${r.empty} errors=${r.errors}`,
            ),
          )
          .catch((err) => console.error("[scheduled] showroom sales sweep failed:", err)),
      );
      return;
    }
    // Unknown trigger — log and ignore.
    console.warn(`scheduled: unhandled cron "${event.cron}"`);
  },
};

/**
 * MCP connector OAuth wrapper (0015).
 *
 * OAuthProvider owns the OAuth endpoints + the `.well-known` metadata, and
 * routes the MCP transport paths (`/mcp`, `/mcp/sse`) to the McpAgent DO with
 * the authenticated grant `props` attached. Everything else falls through to
 * `legacyHandler` (Astro SSR + Hono `/api/*` + Cloudflare Agents), which also
 * renders the `/oauth/authorize` consent screen.
 *
 * NOTE: OAuthProvider only implements `fetch`. The default export below
 * therefore delegates `fetch` to the provider but wires `scheduled` and
 * `email` straight to `legacyHandler` so the cron jobs (permit sync, workflow
 * dispatch, auto-heal, showroom monitor, Gmail ingest) and inbound email
 * routing keep working.
 */
const oauthProvider = new OAuthProvider({
  apiHandlers: {
    "/mcp": RemodelMcpAgent.serve("/mcp", { binding: "REMODEL_MCP" }),
    "/mcp/sse": RemodelMcpAgent.serveSSE("/mcp/sse", { binding: "REMODEL_MCP" }),
  },
  defaultHandler: legacyHandler,
  authorizeEndpoint: "/oauth/authorize",
  tokenEndpoint: "/oauth/token",
  clientRegistrationEndpoint: "/oauth/register",
  scopesSupported: ["remodel"],
});

const handler: ExportedHandler<Env> = {
  fetch: (request, env, ctx) => oauthProvider.fetch(request, env, ctx),
  scheduled: (event, env, ctx) => legacyHandler.scheduled!(event, env, ctx),
  email: (message, env, ctx) => legacyHandler.email!(message, env, ctx),
};

export default handler;
